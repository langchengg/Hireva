@MainActor
@Suite(.serialized)
struct GenerationRequestSnapshotTests {
    @Test
    func providerConfigurationRemainsFrozenWhileRetrievalIsSuspended() async throws {
        let retrieval = SuspendedRequestRetrieval()
        let remote = RequestRecordingClient()
        let app = try makeApp(retrieval: retrieval, client: remote)
        let session = try app.sessionRepository.createSession(mode: .mock)
        app.currentSession = session
        let question = makeQuestion(sessionID: session.id, id: "frozen-provider")
        let original = try #require(app.activeRealtimeProvider)
        let request = Task {
            try await app.generateSuggestion(for: question, session: session, transcript: question.questionText, autoGenerated: false)
        }
        await retrieval.waitUntilStarted(question.questionText)
        var changed = original
        changed.model = "replacement-model"
        changed.name = "Replacement provider"
        changed.baseURL = "https://replacement.example.invalid"
        app.saveProviderConfiguration(changed)
        #expect(app.activeRealtimeProvider?.model == changed.model)
        await retrieval.release(question.questionText)
        try await request.value
        await app.stageBTask?.value
        let configurations = await remote.configurations()
        #expect(!configurations.isEmpty)
        #expect(configurations.allSatisfy { $0.model == original.model && $0.name == original.name && $0.baseURL == original.baseURL })
        #expect(app.currentSuggestion?.modelName == original.model)
        #expect(app.currentSuggestion?.providerName == original.name)
        await app.shutdownForTesting()
    }

    @Test
    func localOnlyRequestKeepsModeModelAndProviderAcrossRetrieval() async throws {
        let retrieval = SuspendedRequestRetrieval()
        let remote = RequestRecordingClient()
        let app = try makeApp(retrieval: retrieval, client: remote)
        let original = RequestRecordingLocalProvider()
        let replacement = RequestRecordingLocalProvider()
        app.answerProviderModeOverride = .localQwenPrimary
        app.localLLMProviderOverride = original
        let originalModel = app.selectedQwenModelName
        let session = try app.sessionRepository.createSession(mode: .mock)
        app.currentSession = session
        let question = makeQuestion(sessionID: session.id, id: "frozen-local")
        let request = Task {
            try await app.generateSuggestion(for: question, session: session, transcript: question.questionText, autoGenerated: false)
        }
        await retrieval.waitUntilStarted(question.questionText)
        app.answerProviderModeOverride = .deepSeekPrimary
        app.localLLMProviderOverride = replacement
        app.setSelectedQwenModelName("replacement-local-model")
        await retrieval.release(question.questionText)
        try await request.value
        await app.stageBTask?.value
        let originalRequests = await original.requests()
        #expect(originalRequests.count == 1)
        #expect(originalRequests.first?.modelName == originalModel)
        #expect(await replacement.requests().isEmpty)
        #expect(await remote.configurations().isEmpty)
        #expect(app.currentSuggestion?.sayFirstSource == "ollama_qwen")
        await app.shutdownForTesting()
    }

    @Test
    func cancelledAnswerFallbackCannotPublishWhenItsRetrievalArrivesAfterNewRequest() async throws {
        let retrieval = SuspendedRequestRetrieval()
        let remote = RequestRecordingClient()
        let app = try makeApp(retrieval: retrieval, client: remote)
        app.answerProviderModeOverride = .localQwenPrimary
        app.localLLMProviderOverride = RequestRecordingLocalProvider()
        let session = try app.sessionRepository.createSession(mode: .mock)
        app.currentSession = session
        let first = makeQuestion(sessionID: session.id, id: "old-retry", text: "Explain database transactions and atomicity.")
        let second = makeQuestion(sessionID: session.id, id: "new-retry", text: "Explain database isolation and concurrency.")
        app.lastDetectedQuestion = first
        app.answerCurrentQuestionOrTranscriptNow()
        let oldTask = try #require(app.activeAITask)
        await retrieval.waitUntilStarted(first.questionText)
        app.cancelActiveGenerationForContextChange()
        #expect(oldTask.isCancelled)
        app.lastDetectedQuestion = second
        app.answerCurrentQuestionOrTranscriptNow()
        let newTask = try #require(app.activeAITask)
        await retrieval.waitUntilStarted(second.questionText)
        let newGenerationID = try #require(app.currentGenerationID)
        let newRetrievalDiagnostic = app.lastRAGOperation
        await retrieval.release(first.questionText)
        await oldTask.value
        #expect(app.currentGenerationID == newGenerationID)
        #expect(app.activeQuestionID == second.id)
        #expect(app.currentSuggestion == nil)
        #expect(app.lastRAGOperation == newRetrievalDiagnostic)
        await retrieval.release(second.questionText)
        await newTask.value
        #expect(app.currentSuggestion?.detectedQuestionID == second.id)
        #expect(app.currentSuggestion?.generationID == newGenerationID)
        await app.shutdownForTesting()
    }

    private func makeApp(retrieval: any ContextRetrievalService, client: any LLMClientProtocol) throws -> AppState {
        let database = try TestSupport.makeTemporaryDatabase(prefix: "GenerationRequestSnapshotTests")
        let settings = SettingsRepository(database: database)
        try settings.ensureDefaultProviderConfigurations()
        let provider = try #require(settings.providerConfigurations().first { $0.kind == .deepSeek })
        try settings.setActiveRealtimeProvider(id: provider.id)
        let router = LLMRouter(settingsRepository: settings, clients: [.deepSeek: client])
        let app = AppState(database: database, questionRoutingProvider: HermeticQuestionRoutingProvider(), llmRouter: router, contextRetrievalService: retrieval)
        app.answerProviderModeOverride = .deepSeekPrimary
        app.delayProvider = RequestHoldingDelay()
        return app
    }

    private func makeQuestion(sessionID: String, id: String, text: String = "Explain database transactions and atomicity.") -> DetectedQuestion {
        DetectedQuestion(id: id, sessionID: sessionID, transcriptSegmentID: nil, questionText: text, intent: .technical, answerStrategy: .directAnswer, confidence: 1, reason: "Synthetic ownership fixture", shouldTrigger: true, questionComplete: true, modelName: "fixture", promptVersion: "fixture", createdAt: Date())
    }
}

/// Retrieval deliberately ignores cancellation; each test owns an explicit
/// per-question release and joins every request before shutting down the DB.
private actor SuspendedRequestRetrieval: ContextRetrievalService {
    private var started = Set<String>()
    private var released = Set<String>()
    private var waitingForStart: [String: [CheckedContinuation<Void, Never>]] = [:]
    private var pending: [String: CheckedContinuation<Void, Never>] = [:]

    func waitUntilStarted(_ question: String) async {
        guard !started.contains(question) else { return }
        await withCheckedContinuation { waitingForStart[question, default: []].append($0) }
    }

    func release(_ question: String) {
        released.insert(question)
        pending.removeValue(forKey: question)?.resume()
    }

    func retrieveContextWithTrace(question: String, intent: QuestionIntent, maxCVWords: Int, maxJDWords: Int, strategy: AnswerStrategy?) async throws -> (context: RetrievedContext, trace: RetrievalTrace) {
        started.insert(question)
        waitingForStart.removeValue(forKey: question)?.forEach { $0.resume() }
        if !released.contains(question) {
            await withCheckedContinuation { pending[question] = $0 }
        }
        return (RetrievedContext(cvChunks: [], jobDescriptionChunks: []), RetrievalTrace(id: UUID(), query: question, intent: intent.rawValue, createdAt: Date(), rankedCVChunks: [], rankedJDChunks: [], includedCVChunks: [], includedJDChunks: [], excludedCVChunks: [], excludedJDChunks: [], cvWordsUsed: 0, jdWordsUsed: 0, cvWordBudget: maxCVWords, jdWordBudget: maxJDWords, retrievalLatencyMS: 0, emptyQueryFallbackUsed: false, zeroScoreFallbackUsed: false))
    }
}

private struct RequestHoldingDelay: DelayProvider {
    func sleep(nanoseconds: UInt64) async throws { try await Task.sleep(nanoseconds: 3_600_000_000_000) }
}

private actor RequestRecordingLocalProvider: LocalLLMProvider {
    nonisolated var id: String { "request-recording-local" }
    nonisolated var displayName: String { id }
    private var captured: [LocalLLMRequest] = []
    func requests() -> [LocalLLMRequest] { captured }
    func healthCheck(modelName: String) async -> LocalLLMHealth { .init(ollamaRunning: true, selectedModel: modelName, modelInstalled: true, providerSource: .localQwen, lastError: nil) }
    nonisolated func pullModel(_ modelName: String) -> AsyncThrowingStream<ModelDownloadProgress, Error> { AsyncThrowingStream { $0.finish() } }
    func generateAnswer(request: LocalLLMRequest) async throws -> AsyncThrowingStream<LLMToken, Error> {
        captured.append(request)
        return AsyncThrowingStream { continuation in
            continuation.yield(.init(text: "A database transaction groups operations into an atomic unit. Atomicity means all operations commit together or roll back together, and isolation controls which concurrent changes each transaction can observe.", source: .localQwen, modelName: request.modelName))
            continuation.finish()
        }
    }
}

private final class RequestRecordingClient: LLMClientProtocol {
    var providerKind: LLMProviderKind { .deepSeek }
    private let captured = OSAllocatedUnfairLock(initialState: [LLMProviderConfiguration]())
    func configurations() async -> [LLMProviderConfiguration] { snapshot() }
    private func snapshot() -> [LLMProviderConfiguration] { captured.withLock { $0 } }
    private func record(_ configuration: LLMProviderConfiguration) { captured.withLock { $0.append(configuration) } }
    func testConnection(configuration: LLMProviderConfiguration) async throws -> LLMConnectionTestResult { .init(success: true, message: "Synthetic", latencyMS: 0, models: []) }
    func listModels(configuration: LLMProviderConfiguration) async throws -> [LLMModelInfo] { [] }
    func chatCompletion(configuration: LLMProviderConfiguration, messages: [LLMChatMessage], responseFormat: LLMResponseFormat?, options: LLMRequestOptions) async throws -> LLMChatResult {
        record(configuration)
        return .init(content: "{\"strategy\":\"Explanation\",\"say_first\":\"A database transaction groups operations into an atomic unit. Atomicity means all operations commit together or roll back together.\",\"key_points\":[],\"follow_up_ready\":[],\"confidence\":0.9,\"caution\":\"\",\"evidence_used\":[],\"risk_level\":\"low\"}", modelName: configuration.model, providerKind: configuration.kind, providerName: configuration.name, baseURL: configuration.baseURL, latencyMS: 0, isLocal: false, rawResponse: nil)
    }
    func chatCompletionStream(configuration: LLMProviderConfiguration, messages: [LLMChatMessage], responseFormat: LLMResponseFormat?, options: LLMRequestOptions) -> AsyncThrowingStream<String, Error> {
        record(configuration)
        let stageB = messages.contains { $0.content.contains("SAY_FIRST") }
        return AsyncThrowingStream { continuation in
            let answer = "A database transaction groups operations into an atomic unit. Atomicity means all operations commit together or roll back together, and isolation controls which concurrent changes each transaction can observe."
            continuation.yield(stageB ? "STRATEGY: Explanation\nSAY_FIRST: \(answer)\nKEY_POINTS:\n- Commit or roll back atomically.\nFOLLOW_UP_READY:\n- I can explain isolation levels next.\nCAUTION:\n" : answer)
            continuation.finish()
        }
    }
}
