@MainActor
struct RAGFallbackDeadlineTerminalTests {
    @Test(.timeLimit(.minutes(1)), arguments: 0..<20)
    func ragFallbackCannotPublishAfterItsSameIdentityHasFailedTerminal(repetition: Int) async throws {
        // Twenty independent cases retain one explicitly controlled ordering.
        // These synthetic ownership inputs are not a router/model holdout.
        try await exercise(repetition: repetition)
    }

    private func exercise(repetition: Int) async throws {
        let database = try await TestSupport.makeInMemoryDatabase()
        let retrieval = RAGFallbackHeldRetrieval()
        let clock = RAGFallbackControlledClock()
        let client = RAGFallbackNoOutputClient()
        var app: AppState?
        var request: Task<Void, Error>?
        var initialDeadline: Task<Void, Never>?
        var ragDeadline: Task<Void, Never>?
        var stageA: Task<String, Error>?
        var stageB: Task<Void, Never>?
        do {
            let settings = SettingsRepository(database: database)
            try settings.ensureDefaultProviderConfigurations()
            let config = try #require(try settings.providerConfigurations().first { $0.kind == .deepSeek })
            try settings.setActiveRealtimeProvider(id: config.id)
            let state = AppState(database: database,
                questionRoutingProvider: HermeticQuestionRoutingProvider(),
                llmRouter: LLMRouter(settingsRepository: settings, clients: [.deepSeek: client]),
                permissionService: HermeticPermissionService(),
                keychainService: KeychainService(store: InMemoryMockKeychainStore()),
                contextRetrievalService: retrieval, dialogueDefaults: nil)
            app = state
            state.answerProviderModeOverride = .deepSeekPrimary
            state.delayProvider = clock
            state.generationWatchdogDelayProvider = RAGFallbackHeldCooperativeClock()
            let session = try makeContextSession(state, repetition: repetition)
            // The actual UI owner must admit this session before its deadlines.
            state.currentSession = session
            let question = DetectedQuestion(id: "rag-terminal-question-\(repetition)",
                sessionID: session.id, transcriptSegmentID: nil,
                questionText: "Why do you want this role?", intent: .companyFit,
                answerStrategy: .directAnswer, confidence: 1,
                reason: "Synthetic RAG deadline ownership fixture", shouldTrigger: true,
                questionComplete: true, modelName: "fixture", promptVersion: "fixture", createdAt: Date())
            try state.suggestionRepository.saveDetectedQuestion(question)
            let pending = Task { try await state.generateSuggestion(for: question,
                session: session, transcript: question.questionText, autoGenerated: false) }
            request = pending
            // RAG is held until the distinct initial 1.5-second deadline has
            // registered. Scheduling order cannot relabel the two clock calls.
            try await retrieval.waitUntilStarted()
            try await clock.waitUntilInitialRegistered()
            let requiredInitialDeadline: Task<Void, Never> = try #require(state.softFallbackTask)
            initialDeadline = requiredInitialDeadline
            let generationID = try #require(state.currentGenerationID)
            await retrieval.release()
            try await clock.waitUntilRAGRegistered()
            let requiredRAGDeadline: Task<Void, Never> = try #require(state.softFallbackTask)
            ragDeadline = requiredRAGDeadline
            let requiredFirstAnswerWorker: Task<String, Error> = try #require(state.activeGenerationController?.stageATask)
            stageA = requiredFirstAnswerWorker
            let requiredExpansionWorker: Task<Void, Never> = try #require(state.stageBTask)
            stageB = requiredExpansionWorker
            let resolved = try #require(state.lastDetectedQuestion?.taskDescriptor)
            try #require(PromptContextBuilder.usesProfileContext(resolved))
            try #require(state.activeContextSnapshot?.candidateEvidence.contains(where: \.isUsable) == true)
            #expect(await clock.fallbackRequests() == [1_500_000_000, 1_500_000_000])
            #expect(initialDeadline?.isCancelled == true)
            await clock.releaseInitial()
            await initialDeadline?.value
            #expect(state.currentSuggestion == nil)
            #expect(state.streamFirstVisibleTextAt == nil)

            state.markGenerationFailed(generationID: generationID, reason: "Synthetic RAG terminal failure")
            #expect(ragDeadline?.isCancelled == true)
            try #require(state.generationUIState.isTerminal)
            try #require(state.terminalGenerationIDs.contains(generationID))
            // Settle the other real children before taking observations. The
            // only outstanding business callback is the cancelled RAG deadline.
            pending.cancel()
            client.finishStreams()
            _ = await stageA?.result
            await stageB?.value
            _ = await pending.result
            try #require(state.currentGenerationID == generationID)
            #expect(state.softFallbackTask == nil)
            let card = state.currentSuggestion
            let ui = state.generationUIState
            let telemetry = state.currentGenerationTelemetry
            let source = state.finalVisibleSource
            let fallbackUsed = state.softFallbackUsed
            let fallbackLatency = state.softFallbackLatencyMS
            let fallbackShownAt = state.softFallbackShownAt
            let feedback = state.activeActionFeedbacks
            let events = state.recentTranscriptRuntimeEvents
            let callbackDiscards = state.staleCallbackDiscardCount
            let answerDiscards = state.staleAnswerDiscardCount
            let stored = try state.suggestionRepository.suggestions(sessionID: session.id)
            #expect(stored.isEmpty)
            // The real RAG task's delay intentionally ignores cancellation.
            // Its production callback must revalidate ownership before effects.
            await clock.releaseRAG()
            await ragDeadline?.value
            #expect(state.currentSuggestion == card)
            #expect(state.generationUIState == ui)
            #expect(state.currentGenerationTelemetry == telemetry)
            #expect(state.finalVisibleSource == source)
            #expect(state.softFallbackUsed == fallbackUsed)
            #expect(state.softFallbackLatencyMS == fallbackLatency)
            #expect(state.softFallbackShownAt == fallbackShownAt)
            #expect(state.activeActionFeedbacks == feedback)
            #expect(state.recentTranscriptRuntimeEvents == events)
            #expect(state.staleCallbackDiscardCount == callbackDiscards)
            #expect(state.staleAnswerDiscardCount == answerDiscards)
            #expect(!state.isStreamingSayFirst)
            #expect(!state.isExpandingSuggestionCard)
            #expect(!state.isActionLoading(ActionID.generateAnswer))
            #expect(try state.suggestionRepository.suggestions(sessionID: session.id) == stored)
            await state.shutdownForTesting()
            #expect(state.generationCoordinator.pendingCleanupTaskCount == 0)
            try database.close()
        } catch {
            request?.cancel(); initialDeadline?.cancel(); ragDeadline?.cancel()
            stageA?.cancel(); stageB?.cancel()
            client.finishStreams()
            await clock.releaseAll()
            await retrieval.release()
            await initialDeadline?.value; await ragDeadline?.value
            _ = await stageA?.result; await stageB?.value; _ = await request?.result
            await app?.shutdownForTesting()
            try? database.close()
            throw error
        }
    }

