    }
}

private actor RAGFallbackHeldRetrieval: ContextRetrievalService {
    private let started = AsyncStream<Void>.makeStream(bufferingPolicy: .bufferingNewest(1))
    private var released = false
    private var waiter: CheckedContinuation<Void, Never>?
    func waitUntilStarted() async throws {
        _ = try await TestEventWaitTrace(label: "rag_terminal.retrieval").nextEvent(in: started.stream, event: "registered")
    }
    func release() { released = true; waiter?.resume(); waiter = nil }
    func retrieveContextWithTrace(question: String, intent: QuestionIntent,
        maxCVWords: Int, maxJDWords: Int, strategy: AnswerStrategy?) async throws -> (context: RetrievedContext, trace: RetrievalTrace) {
        started.continuation.yield(()); started.continuation.finish()
        if !released { await withCheckedContinuation { waiter = $0 } }
        return (.init(cvChunks: [], jobDescriptionChunks: []),
            .init(id: UUID(), query: question, intent: intent.rawValue, createdAt: Date(),
                rankedCVChunks: [], rankedJDChunks: [], includedCVChunks: [], includedJDChunks: [],
                excludedCVChunks: [], excludedJDChunks: [], cvWordsUsed: 0, jdWordsUsed: 0,
                cvWordBudget: maxCVWords, jdWordBudget: maxJDWords, retrievalLatencyMS: 0,
                emptyQueryFallbackUsed: false, zeroScoreFallbackUsed: false))
    }
}

private actor RAGFallbackControlledClock: DelayProvider {
    private let initial = AsyncStream<Void>.makeStream(bufferingPolicy: .bufferingNewest(1))
    private let rag = AsyncStream<Void>.makeStream(bufferingPolicy: .bufferingNewest(1))
    private var calls: [UInt64] = []
    private var initialReleased = false
    private var ragReleased = false
    private var initialWaiter: CheckedContinuation<Void, Never>?
    private var ragWaiter: CheckedContinuation<Void, Never>?
    func sleep(nanoseconds: UInt64) async throws {
        guard nanoseconds == 1_500_000_000 else {
            try await Task.sleep(nanoseconds: 3_600_000_000_000)
            return
        }
        calls.append(nanoseconds)
        switch calls.count {
        case 1:
            initial.continuation.yield(()); initial.continuation.finish()
            if !initialReleased { await withCheckedContinuation { initialWaiter = $0 } }
        case 2:
            rag.continuation.yield(()); rag.continuation.finish()
            if !ragReleased { await withCheckedContinuation { ragWaiter = $0 } }
        default:
            Issue.record("Unexpected third 1.5-second fallback deadline")
            throw CancellationError()
        }
    }
    func waitUntilInitialRegistered() async throws {
        _ = try await TestEventWaitTrace(label: "rag_terminal.initial_clock").nextEvent(in: initial.stream, event: "registered")
    }
    func waitUntilRAGRegistered() async throws {
        _ = try await TestEventWaitTrace(label: "rag_terminal.rag_clock").nextEvent(in: rag.stream, event: "registered")
    }
    func fallbackRequests() -> [UInt64] { calls }
    func releaseInitial() { initialReleased = true; initialWaiter?.resume(); initialWaiter = nil }
    func releaseRAG() { ragReleased = true; ragWaiter?.resume(); ragWaiter = nil }
    func releaseAll() { releaseInitial(); releaseRAG() }
}

private struct RAGFallbackHeldCooperativeClock: DelayProvider {
    func sleep(nanoseconds: UInt64) async throws { try await Task.sleep(nanoseconds: 3_600_000_000_000) }
}

// This transport creates no Task. Its actual stream continuations are protected
// by one Sendable lock and are explicitly finished before application shutdown.
private final class RAGFallbackNoOutputClient: LLMClientProtocol, Sendable {
    let providerKind: LLMProviderKind = .deepSeek
    private let streams = OSAllocatedUnfairLock(initialState: [UUID: AsyncThrowingStream<String, Error>.Continuation]())
    func testConnection(configuration: LLMProviderConfiguration) async throws -> LLMConnectionTestResult { throw CancellationError() }
    func listModels(configuration: LLMProviderConfiguration) async throws -> [LLMModelInfo] { throw CancellationError() }
    func chatCompletion(configuration: LLMProviderConfiguration, messages: [LLMChatMessage],
        responseFormat: LLMResponseFormat?, options: LLMRequestOptions) async throws -> LLMChatResult {
        Issue.record("The held Stage A/RAG fixture unexpectedly made a non-streaming provider request")
        throw CancellationError()
    }
    func chatCompletionStream(configuration: LLMProviderConfiguration, messages: [LLMChatMessage],
        responseFormat: LLMResponseFormat?, options: LLMRequestOptions) -> AsyncThrowingStream<String, Error> {
        let pair = AsyncThrowingStream<String, Error>.makeStream()
        let id = UUID()
        let storage = streams
        storage.withLock { $0[id] = pair.continuation }
        pair.continuation.onTermination = { _ in storage.withLock { $0[id] = nil } }
        return pair.stream
    }
    func finishStreams() {
        let owned = streams.withLock { values in
            let result = Array(values.values); values.removeAll(); return result
        }
        owned.forEach { $0.finish(throwing: CancellationError()) }
    }
}
