import Foundation
import Testing
@testable import Hireva

@MainActor
struct InitialFallbackTerminalBoundaryTests {
    @Test(.serialized, .timeLimit(.minutes(1)), arguments: 0..<20)
    func initialFallbackCannotPublishAfterItsGenerationHasFailedTerminal(order: Int) async throws {
        // Twenty repetitions of one explicit ordering, each fully joined before
        // the next fixture. This is a race regression, not a latency benchmark.
        do {
            let database = try AppDatabase(inMemory: true)
            let retrieval = InitialFallbackHeldRetrieval()
            let clock = InitialFallbackNoncooperativeDelay()
            var ownedApp: AppState?
            var ownedRequest: Task<Void, Error>?
            var fallback: Task<Void, Never>?
            do {
                let settings = SettingsRepository(database: database)
                try settings.ensureDefaultProviderConfigurations()
                let configuration = try #require(try settings.providerConfigurations().first { $0.kind == .deepSeek })
                try settings.setActiveRealtimeProvider(id: configuration.id)
                let client = InitialFallbackNoIOClient()
                let app = AppState(database: database,
                    questionRoutingProvider: HermeticQuestionRoutingProvider(),
                    llmRouter: LLMRouter(settingsRepository: settings, clients: [.deepSeek: client]),
                    permissionService: HermeticPermissionService(),
                    keychainService: KeychainService(store: InMemoryMockKeychainStore()),
                    contextRetrievalService: retrieval,
                    dialogueDefaults: nil)
                ownedApp = app
                app.answerProviderModeOverride = .deepSeekPrimary
                app.delayProvider = clock
                app.generationWatchdogDelayProvider = InitialFallbackHeldCooperativeDelay()
                let session = try app.sessionRepository.createSession(mode: .mock)
                app.currentSession = session
                let question = DetectedQuestion(id: "initial-fallback-\(order)", sessionID: session.id,
                    transcriptSegmentID: nil, questionText: "Explain database transactions and atomicity.",
                    intent: .technical, answerStrategy: .directAnswer, confidence: 1,
                    reason: "Synthetic initial fallback terminal race", shouldTrigger: true,
                    questionComplete: true, modelName: "fixture", promptVersion: "fixture", createdAt: Date())
                try app.suggestionRepository.saveDetectedQuestion(question)
                let request = Task { try await app.generateSuggestion(for: question,
                    session: session, transcript: question.questionText, autoGenerated: false) }
                ownedRequest = request
                try await retrieval.waitUntilStarted()
                try await clock.waitUntilStarted()
                let requiredInitialFallback: Task<Void, Never> = try #require(app.softFallbackTask)
                fallback = requiredInitialFallback
                let generationID = try #require(app.currentGenerationID)
                app.markGenerationFailed(generationID: generationID, reason: "Synthetic terminal decision")
                #expect(fallback?.isCancelled == true)
                #expect(app.currentSuggestion == nil)
                let state = app.generationUIState
                let source = app.finalVisibleSource
                let fallbackUsed = app.softFallbackUsed
                let fallbackLatency = app.softFallbackLatencyMS
                let feedback = app.activeActionFeedbacks
                let telemetry = app.currentGenerationTelemetry
                await clock.release()
                await fallback?.value
                #expect(app.generationUIState == state)
                #expect(app.finalVisibleSource == source)
                #expect(app.softFallbackUsed == fallbackUsed)
                #expect(app.softFallbackLatencyMS == fallbackLatency)
                #expect(app.activeActionFeedbacks == feedback)
                #expect(app.currentGenerationTelemetry == telemetry)
                #expect(app.currentSuggestion == nil)
                #expect(try app.suggestionRepository.suggestions(sessionID: session.id).isEmpty)
                await retrieval.release()
                try await request.value
                await app.shutdownForTesting()
                #expect(app.generationCoordinator.pendingCleanupTaskCount == 0)
                try database.close()
            } catch {
                ownedRequest?.cancel()
                fallback?.cancel()
                await clock.release()
                await retrieval.release()
                await fallback?.value
                _ = await ownedRequest?.result
                await ownedApp?.shutdownForTesting()
                try? database.close()
                throw error
            }
        }
    }
}

private actor InitialFallbackNoncooperativeDelay: DelayProvider {
    private let started = AsyncStream<Void>.makeStream(bufferingPolicy: .bufferingNewest(1))
    private var released = false
    private var waiter: CheckedContinuation<Void, Never>?
    func sleep(nanoseconds: UInt64) async throws {
        started.continuation.yield(())
        started.continuation.finish()
        guard !released else { return }
        await withCheckedContinuation { waiter = $0 }
    }
    func waitUntilStarted() async throws {
        _ = try await TestEventWaitTrace(label: "initial_fallback.delay").nextEvent(in: started.stream, event: "registered")
    }
    func release() { released = true; waiter?.resume(); waiter = nil }
}

private actor InitialFallbackHeldRetrieval: ContextRetrievalService {
    private let started = AsyncStream<Void>.makeStream(bufferingPolicy: .bufferingNewest(1))
    private var released = false
    private var waiter: CheckedContinuation<Void, Never>?
    func waitUntilStarted() async throws {
        _ = try await TestEventWaitTrace(label: "initial_fallback.retrieval").nextEvent(in: started.stream, event: "registered")
    }
    func release() { released = true; waiter?.resume(); waiter = nil }
    func retrieveContextWithTrace(question: String, intent: QuestionIntent,
        maxCVWords: Int, maxJDWords: Int, strategy: AnswerStrategy?) async throws -> (context: RetrievedContext, trace: RetrievalTrace) {
        started.continuation.yield(())
        started.continuation.finish()
        if !released { await withCheckedContinuation { waiter = $0 } }
        return (.init(cvChunks: [], jobDescriptionChunks: []),
            .init(id: UUID(), query: question, intent: intent.rawValue, createdAt: Date(),
                rankedCVChunks: [], rankedJDChunks: [], includedCVChunks: [], includedJDChunks: [],
                excludedCVChunks: [], excludedJDChunks: [], cvWordsUsed: 0, jdWordsUsed: 0,
                cvWordBudget: maxCVWords, jdWordBudget: maxJDWords, retrievalLatencyMS: 0,
                emptyQueryFallbackUsed: false, zeroScoreFallbackUsed: false))
    }
}

private struct InitialFallbackHeldCooperativeDelay: DelayProvider {
    func sleep(nanoseconds: UInt64) async throws { try await Task.sleep(nanoseconds: 3_600_000_000_000) }
}

// The held retrieval must prevent every real answer-provider request.
private final class InitialFallbackNoIOClient: LLMClientProtocol, Sendable {
    let providerKind: LLMProviderKind = .deepSeek
    func testConnection(configuration: LLMProviderConfiguration) async throws -> LLMConnectionTestResult { throw CancellationError() }
    func listModels(configuration: LLMProviderConfiguration) async throws -> [LLMModelInfo] { throw CancellationError() }
    func chatCompletion(configuration: LLMProviderConfiguration, messages: [LLMChatMessage],
        responseFormat: LLMResponseFormat?, options: LLMRequestOptions) async throws -> LLMChatResult {
        Issue.record("Held retrieval unexpectedly reached the answer provider")
        throw CancellationError()
    }
    func chatCompletionStream(configuration: LLMProviderConfiguration, messages: [LLMChatMessage],
        responseFormat: LLMResponseFormat?, options: LLMRequestOptions) -> AsyncThrowingStream<String, Error> {
        Issue.record("Held retrieval unexpectedly reached the answer provider")
        return AsyncThrowingStream { $0.finish(throwing: CancellationError()) }
    }
}
