    @Test(.timeLimit(.minutes(1)), arguments: [false, true])
    func providerFailureCardPublicationCannotFinishReplacementAction(replaceAtPublication: Bool) async throws {
        let gate = TerminalProviderGate()
        let app = try makeApp(client: TerminalStageBClient(gate: gate, failExpansion: true))
        let cleanup = TerminalFixtureCleanup(app: app, gate: gate)
        try await cleanup.run {
            let session = try app.sessionRepository.createSession(mode: .mock)
            app.currentSession = session
            let original = makeQuestion(sessionID: session.id, id: "synthetic-failure-old-" + UUID().uuidString)
            try app.suggestionRepository.saveDetectedQuestion(original)
            let request = Task {
                try await app.generateSuggestion(for: original, session: session,
                    transcript: original.questionText, autoGenerated: false)
            }
            cleanup.own(request)
            try await request.value
            try await gate.waitForOwnedStart()
            let stageB = try #require(app.stageBTask)
            cleanup.own(stageB)
            let originalID = try #require(app.currentGenerationID)
            let first = try #require(app.currentSuggestion)
            _ = try #require(app.completeSubstantiveProviderFirstAnswerAfterTimeout(first,
                question: original, requestStart: Date()))
            var replacement = makeQuestion(sessionID: session.id, id: "synthetic-failure-new-" + UUID().uuidString)
            replacement.questionText = "Explain transaction isolation and visibility."
            try app.suggestionRepository.saveDetectedQuestion(replacement)
            let replacementID = UUID().uuidString
            var sawPublication = false, replaced = false
            let observation = app.liveInterview.suggestionUpdates.dropFirst().sink { incoming in
                guard incoming?.generationID == originalID, incoming?.stageBCompleted == true else { return }
                sawPublication = true
                guard replaceAtPublication, !replaced else { return }
                replaced = true
                app.startGenerationRequest(triggerPath: .regenerate) { _ in }
                if let root = app.activeAITask { cleanup.own(root) }
                guard let requestID = app.generationCoordinator.activeRequest?.id else {
                    Issue.record("The replacement must own its actual request")
                    return
                }
                app.activateGeneration(question: replacement, generationID: replacementID,
                    triggerPath: .regenerate, requestStart: Date(), source: .systemAudio,
                    speaker: .unknown, requestID: requestID)
                let answer = Task<String, Error> { "Finite replacement-owned answer" }
                cleanup.own(answer)
                app.registerStageATask(answer, generationID: replacementID)
                app.beginAction(ActionID.generateAnswer, title: "Synthetic replacement pending", message: "Synthetic pending answer")
            }
            defer { observation.cancel() }
            await gate.release()
            await stageB.value
            #expect(sawPublication, "The real provider failure must reach qualified first-answer publication.")
            #expect(replaced == replaceAtPublication)
            if replaceAtPublication {
                #expect(app.currentGenerationID == replacementID)
                #expect(app.activeQuestionID == replacement.id)
                #expect(app.currentSuggestion == nil)
                #expect(app.generationUIState == .preparing(questionID: replacement.id,
                    generationID: replacementID, triggerPath: .regenerate))
                #expect(app.isActionLoading(ActionID.generateAnswer))
                #expect(app.latestActionFeedback(for: ActionID.generateAnswer)?.title == "Synthetic replacement pending")
                #expect(app.latestActionFeedback(for: ActionID.generateAnswer)?.kind == .loading)
            } else {
                #expect(app.currentGenerationID == originalID)
                #expect(app.currentSuggestion?.stageBCompleted == true)
                #expect(!app.isActionLoading(ActionID.generateAnswer))
                #expect(app.latestActionFeedback(for: ActionID.generateAnswer)?.kind == .warning)
            }
            await app.generationCoordinator.drainRetiredTasks()
            let stored = try app.suggestionRepository.suggestions(sessionID: session.id)
            #expect(stored.allSatisfy { $0.generationID == originalID && $0.detectedQuestionID == original.id },
                "Old persistence cannot borrow the replacement question or generation.")
            if !replaceAtPublication { #expect(stored.count == 1) }
        }
    }

