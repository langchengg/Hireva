private struct TerminalFixtureAbort: Error {}

// Retain test-launched tasks across thrown fixture errors and normal completion.
// Cleanup releases the noncooperative gate before joining; it runs in the test.
@MainActor
private final class TerminalFixtureCleanup {
    private let app: AppState
    private let gate: TerminalProviderGate
    private var cancellations: [() -> Void] = []
    private var joins: [() async -> Void] = []
    private var closed = false
    init(app: AppState, gate: TerminalProviderGate) { self.app = app; self.gate = gate }
    func own<T, E: Error>(_ task: Task<T, E>) {
        cancellations.append { task.cancel() }
        joins.append { _ = await task.result }
    }
    func run(_ operation: () async throws -> Void) async throws {
        do { try await operation() }
        catch { await close(); throw error }
        await close()
    }
    private func close() async {
        guard !closed else { return }
        closed = true
        let currentlyRegisteredStageB = app.stageBTask
        cancellations.forEach { $0() }
        currentlyRegisteredStageB?.cancel()
        await gate.release()
        for join in joins { await join() }
        await currentlyRegisteredStageB?.value
        await app.shutdownForTesting()
    }
}

/// Noncooperative work is bounded by an explicit test-owned release. Each test
/// joins the pending production task before fixture shutdown.
private actor TerminalProviderGate {
    nonisolated let id = UUID().uuidString
    private var starts = 0
    private var released = false
    private let startedEvents: AsyncStream<Void>
    private let startedContinuation: AsyncStream<Void>.Continuation

    init() {
        let pair = AsyncStream<Void>.makeStream(bufferingPolicy: .bufferingNewest(1))
        startedEvents = pair.stream
        startedContinuation = pair.continuation
    }
    private var operationWaiter: CheckedContinuation<Void, Never>?

    func startCount() -> Int { starts }
    nonisolated func markPhase(_ phase: String) {
        // Test-only control metadata. An immutable gate identity and monotonic
        // timestamps distinguish a provider step from executor queueing.
        print("[TerminalFixturePhase] gate=\(id) phase=\(phase) uptimeNS=\(DispatchTime.now().uptimeNanoseconds) priorityRaw=\(Task.currentPriority.rawValue)")
    }
    func waitUntilStarted() async throws {
        markPhase("readiness_wait_started")
        guard starts == 0 else { return }
        let events = startedEvents
        try await GenerationCoordinator.withTimeout(seconds: 3) {
            for await _ in events { return }
            try Task.checkCancellation()
        }
    }
    // This admission test holds a test-created child, not a provider deadline.
    // Its owning test cancellation bounds scheduling and the fixture always
    // releases and joins the original child before shutting down its App.
    func waitForOwnedStart() async throws {
        markPhase("owned_entry_wait_started")
        guard starts == 0 else { return }
        for await _ in startedEvents {
            try Task.checkCancellation()
            return
        }
        throw CancellationError()
    }
    func suspend() async {
        markPhase("controlled_provider_entered")
        starts += 1
        startedContinuation.yield(())
        startedContinuation.finish()
        guard !released else { return }
        await withCheckedContinuation { operationWaiter = $0 }
    }
    func release() {
        released = true
        operationWaiter?.resume()
        operationWaiter = nil
    }
}

@MainActor
private final class TerminalPublicationSignal {
    private var fired = false
    private let events: AsyncStream<Void>
    private let continuation: AsyncStream<Void>.Continuation
    init() {
        let pair = AsyncStream<Void>.makeStream(bufferingPolicy: .bufferingNewest(1))
        events = pair.stream
        continuation = pair.continuation
    }
    func signal() {
        fired = true
        continuation.yield(())
        continuation.finish()
    }
    func wait() async throws {
        guard !fired else { return }
        let events = events
        try await GenerationCoordinator.withTimeout(seconds: 3) {
            for await _ in events { return }
            try Task.checkCancellation()
        }
    }
}

