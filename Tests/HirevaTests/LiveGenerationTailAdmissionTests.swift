@MainActor
struct LiveGenerationTailAdmissionTests {
    @Test(.timeLimit(.minutes(1)), arguments: ["question", "generation", "token"])
    func generationEntryResetCannotEraseSubscriberReplacement(boundary: String) async throws {
        try await withApplication { app, session in
            let original = question(session: session, text: "Explain database transactions and atomicity.")
            let replacement = question(session: session, text: "Explain transaction isolation and visibility.")
            try app.suggestionRepository.saveDetectedQuestion(original)
            try app.suggestionRepository.saveDetectedQuestion(replacement)
            let replacementID = UUID().uuidString
            let marker = "Synthetic replacement preview."
            let time = Date(timeIntervalSince1970: 1_234_567)
            var replaced = false
            var replacementRoot: Task<Void, Never>?
            @MainActor func replace() {
                guard !replaced else { return }
                replaced = true
                app.startGenerationRequest(triggerPath: .regenerate) { _ in }
                replacementRoot = app.activeAITask
                guard let requestID = app.generationCoordinator.activeRequest?.id else {
                    Issue.record("The subscriber must own its replacement request")
                    return
                }
                app.activateGeneration(question: replacement, generationID: replacementID,
                    triggerPath: .regenerate, requestStart: Date(), source: .systemAudio,
                    speaker: .unknown, requestID: requestID)
                app.lastDetectedQuestion = replacement
                app.lastDetectedQuestionText = replacement.questionText
                app.streamFirstTokenAt = time
                app.streamedSayFirst = marker
                app.finalVisibleSource = marker
                app.softFallbackUsed = true
                app.softFallbackLatencyMS = 828
                app.currentSuggestionSetAt = time
                app.beginAction(ActionID.generateAnswer, title: marker, message: marker)
            }
            let observation: AnyCancellable
            switch boundary {
            case "question":
                observation = app.liveInterview.detectedQuestionUpdates.dropFirst().sink { value in
                    if value?.id == original.id { replace() }
                }
            case "generation":
                observation = app.liveInterview.generationStateUpdates.dropFirst().sink { value in
                    if case .generatingFirstAnswer(let questionID, _, _) = value,
                        questionID == original.id { replace() }
                }
            default:
                observation = app.streamFirstTokenAtUpdates.dropFirst().sink { value in
                    if value == nil, case .generatingFirstAnswer(let questionID, _, _) = app.generationUIState,
                        questionID == original.id { replace() }
                }
            }
            defer { observation.cancel() }
            do {
                try await app.generateSuggestion(for: original, session: session,
                    transcript: original.questionText, autoGenerated: false,
                    localProvider: HermeticQuestionRoutingProvider(), answerMode: .localQwenPrimary)
            } catch is CancellationError {
                #expect(replaced, "Only the explicitly replaced old request may cancel.")
            }
            #expect(replaced)
            #expect(app.lastDetectedQuestionText == replacement.questionText)
            #expect(app.currentGenerationID == replacementID)
            #expect(app.activeQuestionID == replacement.id)
            #expect(app.generationUIState == .preparing(questionID: replacement.id,
                generationID: replacementID, triggerPath: .regenerate))
            #expect(app.streamFirstTokenAt == time)
            #expect(app.streamedSayFirst == marker)
            #expect(app.finalVisibleSource == marker)
            #expect(app.softFallbackUsed && app.softFallbackLatencyMS == 828)
            #expect(app.currentSuggestionSetAt == time)
            #expect(app.isActionLoading(ActionID.generateAnswer))
            #expect(app.latestActionFeedback(for: ActionID.generateAnswer)?.title == marker)
            await replacementRoot?.value
            app.generationCoordinator.invalidateAndCancel()
            await app.generationCoordinator.drainRetiredTasks()
            #expect(app.generationCoordinator.pendingCleanupTaskCount == 0)
            #expect(try app.suggestionRepository.suggestions(sessionID: session.id).isEmpty)
        }
    }

    @Test(.timeLimit(.minutes(1)), arguments: [false, true], [false, true])
    func firstVisiblePublicationCannotFinishSubscriberReplacement(fallback: Bool, replaceAtPublication: Bool) async throws {
        try await withApplication { app, session in
            let original = question(session: session, text: "Explain database transactions and atomicity.")
            let replacement = question(session: session, text: "Explain transaction isolation and visibility.")
            try app.suggestionRepository.saveDetectedQuestion(original)
            try app.suggestionRepository.saveDetectedQuestion(replacement)
            let originalID = UUID().uuidString, replacementID = UUID().uuidString
            app.activateGeneration(question: original, generationID: originalID,
                triggerPath: .manualGenerate, requestStart: Date(), source: .systemAudio, speaker: .unknown)
            #expect(app.displaySuggestionIfAligned(card(question: original, generationID: originalID,
                snapshotID: session.contextSnapshotID, answer: atomicityAnswer),
                question: original, generationID: originalID, triggerPath: .manualGenerate))
            _ = try #require(app.currentSuggestion)
            app.beginAction(ActionID.generateAnswer, title: "Synthetic original answer", message: "Synthetic operation")
            var sawFirstVisiblePublication = false, replaced = false
            var replacementRoot: Task<Void, Never>?
            var replacementAnswer: Task<String, Error>?
            var acceptedReplacement: SuggestionCard?
            var replacementVisibleStateSetAt: Date?
            let observation = app.generationTelemetryUpdates.dropFirst().sink { incoming in
                guard incoming.generationID == originalID, incoming.firstVisibleAt != nil else { return }
                sawFirstVisiblePublication = true
                guard replaceAtPublication, !replaced else { return }
                replaced = true
                app.startGenerationRequest(triggerPath: .regenerate) { _ in }
                replacementRoot = app.activeAITask
                guard let requestID = app.generationCoordinator.activeRequest?.id else {
                    Issue.record("The subscriber must own its replacement request")
                    return
                }
                app.activateGeneration(question: replacement, generationID: replacementID,
                    triggerPath: .regenerate, requestStart: Date(), source: .systemAudio,
                    speaker: .unknown, requestID: requestID)
                let answer = Task<String, Error> { "Finite replacement-owned answer" }
                replacementAnswer = answer
                app.registerStageATask(answer, generationID: replacementID)
                #expect(app.displaySuggestionIfAligned(card(question: replacement, generationID: replacementID,
                    snapshotID: session.contextSnapshotID, answer: isolationAnswer),
                    question: replacement, generationID: replacementID, triggerPath: .regenerate))
                acceptedReplacement = app.currentSuggestion
                app.beginAction(ActionID.generateAnswer, title: "Synthetic replacement answer", message: "Synthetic operation")
                replacementVisibleStateSetAt = app.firstVisibleStateSetAt
            }
            app.markFirstVisibleAnswer(generationID: originalID, fallback: fallback)
            observation.cancel()
            #expect(sawFirstVisiblePublication, "The fixture must reach the real first-visible publication")
            if replaceAtPublication {
                #expect(replaced)
                #expect(acceptedReplacement != nil, "Q2 must pass the production publication guard")
                #expect(app.currentSuggestion == acceptedReplacement)
                #expect(app.currentGenerationID == replacementID)
                #expect(app.activeQuestionID == replacement.id)
                #expect(app.currentGenerationTelemetry.generationID == replacementID)
                #expect(app.currentGenerationTelemetry.questionID == replacement.id)
                #expect(app.currentGenerationTelemetry.firstVisibleAt == nil)
                #expect(app.currentGenerationTelemetry.fallbackShownAt == nil,
                    "Q1 fallback timing must not be written into Q2")
                #expect(app.firstVisibleStateSetAt == replacementVisibleStateSetAt)
                #expect(app.isActionLoading(ActionID.generateAnswer),
                    "Q1's visible-answer tail must not finish Q2's action")
                #expect(app.generationCoordinator.stageATask == replacementAnswer)
                #expect(replacementAnswer?.isCancelled == false)
            } else {
                #expect(!replaced)
                #expect(app.currentGenerationID == originalID)
                #expect(app.currentGenerationTelemetry.firstVisibleAt != nil)
                #expect((app.currentGenerationTelemetry.fallbackShownAt != nil) == fallback)
                #expect(app.firstVisibleStateSetAt != nil)
                #expect(!app.isActionLoading(ActionID.generateAnswer),
                    "Normal first-visible publication still finishes its own action")
            }
            await replacementRoot?.value
            _ = await replacementAnswer?.result
            app.generationCoordinator.invalidateAndCancel()
            await app.generationCoordinator.drainRetiredTasks()
            #expect(app.generationCoordinator.pendingCleanupTaskCount == 0)
        }
    }

    @Test(.timeLimit(.minutes(1)), arguments: [false, true], [false, true])
    func stateTelemetryPublicationCannotWriteErrorOrMixedAuditIntoReplacement(failed: Bool, replaceAtPublication: Bool) async throws {
        try await withApplication { app, session in
            let original = question(session: session, text: "Explain database transactions and atomicity.")
            let replacement = question(session: session, text: "Explain transaction isolation and visibility.")
            try app.suggestionRepository.saveDetectedQuestion(original)
            try app.suggestionRepository.saveDetectedQuestion(replacement)
            let originalID = UUID().uuidString, replacementID = UUID().uuidString
            app.activateGeneration(question: original, generationID: originalID,
                triggerPath: .manualGenerate, requestStart: Date(), source: .systemAudio, speaker: .unknown)
            #expect(app.displaySuggestionIfAligned(card(question: original, generationID: originalID,
                snapshotID: session.contextSnapshotID, answer: atomicityAnswer),
                question: original, generationID: originalID, triggerPath: .manualGenerate))
            _ = try #require(app.currentSuggestion)
            let oldReason = "Synthetic original transport failure"
            let oldState: GenerationUIState = failed
                ? .failed(questionID: original.id, generationID: originalID, triggerPath: .manualGenerate, reason: oldReason)
                : .expandingFullAnswer(questionID: original.id, generationID: originalID, triggerPath: .manualGenerate)
            var sawStatePublication = false, replaced = false
            var replacementRoot: Task<Void, Never>?
            var replacementAnswer: Task<String, Error>?
            var acceptedReplacement: SuggestionCard?
            let observation = app.generationTelemetryUpdates.dropFirst().sink { incoming in
                guard incoming.generationID == originalID, incoming.generationState == oldState.displayName else { return }
                sawStatePublication = true
                guard replaceAtPublication, !replaced else { return }
                replaced = true
                app.startGenerationRequest(triggerPath: .regenerate) { _ in }
                replacementRoot = app.activeAITask
                guard let requestID = app.generationCoordinator.activeRequest?.id else {
                    Issue.record("The subscriber must own its replacement request")
                    return
                }
                app.activateGeneration(question: replacement, generationID: replacementID,
                    triggerPath: .regenerate, requestStart: Date(), source: .systemAudio,
                    speaker: .unknown, requestID: requestID)
                let answer = Task<String, Error> { "Finite replacement-owned answer" }
                replacementAnswer = answer
                app.registerStageATask(answer, generationID: replacementID)
                #expect(app.displaySuggestionIfAligned(card(question: replacement, generationID: replacementID,
                    snapshotID: session.contextSnapshotID, answer: isolationAnswer),
                    question: replacement, generationID: replacementID, triggerPath: .regenerate))
                acceptedReplacement = app.currentSuggestion
                app.beginAction(ActionID.generateAnswer, title: "Synthetic replacement answer", message: "Synthetic operation")
            }
            // The earlier qualified-card publication legitimately recorded
            // answer.state.updated. Keep that history and observe only the
            // records newly admitted by this state-entry invocation.
            let preexistingAuditIDs = Set(app.diagnosticsState.recentEvents.map(\.id))
            app.setGenerationUIState(oldState, generationID: originalID)
            observation.cancel()
            #expect(sawStatePublication, "The fixture must reach the real state-telemetry publication")
            let followingAudit = app.diagnosticsState.recentEvents.filter {
                !preexistingAuditIDs.contains($0.id) &&
                    $0.name == "answer.state.updated" && $0.generationID == originalID
            }
            #expect(app.generationCoordinator.terminalGenerationIDs.contains(originalID) == failed,
                "A legitimately accepted old terminal fence remains historical authority")
            if replaceAtPublication {
                #expect(replaced)
                #expect(acceptedReplacement != nil, "Q2 must pass the production publication guard")
                #expect(app.currentSuggestion == acceptedReplacement)
                #expect(app.currentGenerationID == replacementID)
                #expect(app.activeQuestionID == replacement.id)
                #expect(app.generationUIState == .preparing(questionID: replacement.id,
                    generationID: replacementID, triggerPath: .regenerate))
                #expect(app.currentGenerationTelemetry.generationID == replacementID)
                #expect(app.currentGenerationTelemetry.questionID == replacement.id)
                #expect(app.currentGenerationTelemetry.generationState == GenerationUIState.preparing(
                    questionID: replacement.id, generationID: replacementID, triggerPath: .regenerate).displayName)
                #expect(app.currentGenerationTelemetry.failureReason == nil,
                    "The old failure must not acquire Q2 telemetry")
                #expect(followingAudit.isEmpty,
                    "The old state caller must stop before a lifecycle wrapper borrows Q2 presentation")
                #expect(app.isActionLoading(ActionID.generateAnswer))
                #expect(app.generationCoordinator.stageATask == replacementAnswer)
                #expect(replacementAnswer?.isCancelled == false)
            } else {
                #expect(!replaced)
                #expect(app.generationUIState == oldState)
                #expect(app.currentGenerationTelemetry.generationState == oldState.displayName)
                #expect(app.currentGenerationTelemetry.failureReason == (failed ? oldReason : nil))
                #expect(followingAudit.count == 1, "Normal state changes still retain their lifecycle audit")
                #expect(followingAudit.first?.questionID == original.id)
                #expect(followingAudit.first?.visibleQuestionText == original.questionText)
                #expect(followingAudit.first?.currentState.contains(oldState.displayName) == true)
            }
            await replacementRoot?.value
            _ = await replacementAnswer?.result
            app.generationCoordinator.invalidateAndCancel()
            await app.generationCoordinator.drainRetiredTasks()
            #expect(app.generationCoordinator.pendingCleanupTaskCount == 0)
        }
    }

    private func withApplication(_ operation: @MainActor (AppState, InterviewSession) async throws -> Void) async throws {
        let folder = FileManager.default.temporaryDirectory
            .appendingPathComponent("HirevaGenerationTail-" + UUID().uuidString, isDirectory: true)
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true,
            attributes: [.posixPermissions: 0o700])
        let store = RuntimeTranscriptTraceStore()
        let database = try AppDatabase(inMemory: true)
        let suite = "com.langcheng.Hireva.tests.generation-tail." + UUID().uuidString
        let defaults = try #require(UserDefaults(suiteName: suite))
        let app = AppState(database: database, questionRoutingProvider: HermeticQuestionRoutingProvider(),
            permissionService: HermeticPermissionService(), keychainService: KeychainService(store: InMemoryMockKeychainStore()),
            verificationMocksEnabled: false, dialogueDefaults: defaults, embeddingProviderResolverOverride: { _ in nil },
            diagnosticsTraceStore: store)
        do {
            try #require(app.settings.effectiveDiagnosticTraceMode == .off)
            app.runtimeTranscriptTraceLogURL = folder.appendingPathComponent("trace.jsonl")
            app.settings.saveTranscriptsLocally = true
            app.settings.diagnosticTraceMode = .fullText
            await app.automaticContextBuildTask?.value
            try Task.checkCancellation()
            let session = try app.createContextBoundSession(mode: .mock, title: "Synthetic generation-tail reentry")
            app.currentSession = session
            try await operation(app, session)
            await app.shutdownForTesting()
            await store.finishPendingOperationsForTesting()
            #expect(app.generationCoordinator.pendingCleanupTaskCount == 0)
            try database.close()
            defaults.removePersistentDomain(forName: suite)
            try FileManager.default.removeItem(at: folder)
        } catch {
            await app.shutdownForTesting()
            await store.finishPendingOperationsForTesting()
            try? database.close()
            defaults.removePersistentDomain(forName: suite)
            try? FileManager.default.removeItem(at: folder)
            throw error
        }
    }

    private let atomicityAnswer = "A database transaction groups operations into an atomic unit. Atomicity means all operations commit together or roll back together, and isolation controls which concurrent changes each transaction can observe."
    private let isolationAnswer = "Transaction isolation controls which concurrent database changes each transaction can observe. The selected isolation level determines permitted anomalies such as dirty reads, nonrepeatable reads and phantoms; stronger levels can require more coordination or retrying conflicting transactions."

    private func question(session: InterviewSession, text: String) -> DetectedQuestion {
        DetectedQuestion(id: UUID().uuidString, sessionID: session.id, transcriptSegmentID: nil,
            questionText: text, intent: .technical, answerStrategy: .technicalExplanation, confidence: 0.99,
            reason: "Synthetic tail admission", shouldTrigger: true, questionComplete: true,
            modelName: "synthetic-no-provider", promptVersion: "synthetic-no-provider", createdAt: Date())
    }

    private func card(question: DetectedQuestion, generationID: String,
                      snapshotID: String?, answer: String) -> SuggestionCard {
        var card = SuggestionCard(id: UUID().uuidString, sessionID: question.sessionID,
            questionID: question.id, strategy: "Explanation", sayFirst: answer, keyPoints: [], followUpReady: [],
            confidence: 0.95, caution: nil, evidenceUsed: [], riskLevel: .low,
            modelName: "synthetic-no-provider", promptVersion: "synthetic-no-provider", rawJSON: nil, createdAt: Date())
        card.detectedQuestionID = question.id
        card.generationID = generationID
        card.questionText = question.questionText
        card.promptQuestionText = question.questionText
        card.promptPrimaryQuestion = question.questionText
        card.contextSnapshotID = snapshotID
        card.stageBCompleted = true
        card.stageBStatus = "completed"
        return card
    }
