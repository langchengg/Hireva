    @Test(.timeLimit(.minutes(1)), arguments: [false, true])
    func liveLocalDeadlineIncludesHeldRoutingAndRetrieval(holdRouting: Bool) async throws {
        let retrieval = LiveRAGCooperativeGate()
        let fixture = try await ManualSnapshotFixture(useAnswerProviderForRouting: holdRouting, retrieval: retrieval)
        let routing = LiveRAGHeldRoutingProvider(answerProvider: fixture.original)
        if holdRouting { fixture.app.localLLMProviderOverride = routing }
        var pending: Task<Void, Error>?
        func cleanup() async throws {
            routing.release(); retrieval.release(); fixture.clock.cancelAll()
            pending?.cancel()
            _ = await pending?.result
            try await fixture.close([])
        }
        do {
            let question = DetectedQuestion(id: UUID().uuidString, sessionID: fixture.session.id,
                transcriptSegmentID: nil, questionText: "Explain database transactions and atomicity.",
                intent: .technical, answerStrategy: .directAnswer, confidence: 1,
                reason: "Synthetic local deadline", shouldTrigger: true, questionComplete: true,
                modelName: "fixture", promptVersion: "fixture", createdAt: Date())
            let task = Task {
                try await fixture.app.generateSuggestion(for: question, session: fixture.session,
                    transcript: question.questionText, autoGenerated: true)
            }
            pending = task
            _ = try await TestEventWaitTrace(label: "live-local-deadline.\(holdRouting)")
                .nextEvent(in: holdRouting ? routing.entered.stream : retrieval.entered.stream, event: "held")
            let identity = try #require(fixture.app.activeGenerationController?.identity)
            let route = fixture.app.generationCoordinator.activeGeneration?.questionRoutingTask
            let rag = fixture.app.generationCoordinator.activeGeneration?.contextRetrievalTask
            let watchdog = try #require(fixture.app.fullCardWatchdogTask)
            let period = fixture.app.generationFullCardWatchdogNanoseconds
            try await fixture.clock.waitUntilPending(nanoseconds: period)
            fixture.clock.advance(by: period)
            await watchdog.value
            if case .timeout = fixture.app.generationUIState {} else { Issue.record("Local deadline must fail without a template answer") }
            #expect(!fixture.app.generationCoordinator.canPublish(identity))
            #expect(holdRouting ? route?.isCancelled == true : rag?.isCancelled == true)
            #expect(!fixture.app.suggestionGenerationStarted)
            #expect(!fixture.app.isActionLoading(ActionID.generateAnswer))
            #expect(fixture.app.currentSuggestion == nil)
            #expect(await fixture.original.requests().isEmpty)
            #expect(fixture.remote.requests().isEmpty)
            #expect(try fixture.app.suggestionRepository.suggestions(sessionID: fixture.session.id).isEmpty)
            try await cleanup()
            #expect(fixture.app.generationCoordinator.pendingCleanupTaskCount == 0)
        } catch {
            try? await cleanup()
            throw error
        }
    }

    @Test(.timeLimit(.minutes(1)), arguments: CancellationAction.allCases, 0..<10)
    func cancelledAnswerFallbackCancelsItsActualRetrievalBeforePublication(action: CancellationAction, repetition: Int) async throws {
        // Twenty joined executions use separate unchanged per-case deadlines;
        // they are not twenty distinct scheduling topologies.
        let retrieval = LiveRAGCooperativeGate()
        let fixture = try await ManualSnapshotFixture(retrieval: retrieval)
        var pending: Task<Void, Never>?
        do {
            let question = DetectedQuestion(id: UUID().uuidString, sessionID: fixture.session.id,
                transcriptSegmentID: nil, questionText: "Explain database transactions and atomicity.",
                intent: .technical, answerStrategy: .directAnswer, confidence: 1,
                reason: "Synthetic RAG ownership", shouldTrigger: true, questionComplete: true,
                modelName: "fixture", promptVersion: "fixture", createdAt: Date())
            fixture.app.lastDetectedQuestion = question
            fixture.app.answerCurrentQuestionOrTranscriptNow()
            let task = try #require(fixture.app.activeAITask)
            pending = task
            _ = try await TestEventWaitTrace(label: "live-rag-\(action.rawValue)-\(repetition)")
                .nextEvent(in: retrieval.entered.stream, event: "retrieval-entered")
            #expect(retrieval.callCount == 1)
            #expect(await fixture.original.requests().isEmpty)
            switch action {
            case .context: fixture.app.cancelActiveGenerationForContextChange()
            case .mode: fixture.app.setSelectedAnswerProviderMode(.deepSeekPrimary)
            }
            #expect(task.isCancelled)
            #expect(fixture.app.currentGenerationID == nil)
            // Always release before joining. The original detached child
            // otherwise survives cancellation of the actual Answer Fallback root.
            retrieval.release()
            try await fixture.join(task)
            #expect(retrieval.observedCancellation,
                "The real retrieval operation must receive cancellation; a stale UI guard alone is insufficient.")
            #expect(retrieval.exited)
            #expect(fixture.app.currentSuggestion == nil)
            #expect(await fixture.original.requests().isEmpty)
            #expect(fixture.remote.requests().isEmpty)
            #expect(try fixture.app.suggestionRepository.suggestions(sessionID: fixture.session.id).isEmpty)
            try await fixture.close([task])
            #expect(fixture.app.generationCoordinator.pendingCleanupTaskCount == 0)
        } catch {
            retrieval.release()
            pending?.cancel()
            await pending?.value
            try? await fixture.close(pending.map { [$0] } ?? [])
            throw error
        }
    }

    @Test(.timeLimit(.minutes(1)))
    func realHybridSettingsAndEmbeddingProviderAreFrozenBeforeRoutingSuspends() async throws {
        let fixture = try await ManualSnapshotFixture(useAnswerProviderForRouting: true)
        let routing = LiveRAGHeldRoutingProvider(answerProvider: fixture.original)
        let original = LiveRAGEmbeddingProbe(providerID: "synthetic-original-embedding", modelName: "synthetic-original-model")
        let replacement = LiveRAGEmbeddingProbe(providerID: "synthetic-replacement-embedding", modelName: "synthetic-replacement-model")
        var pending: Task<Void, Error>?
        do {
            let documents = DocumentRepository(database: fixture.database)
            _ = try documents.saveDocument(type: .cv, title: "Synthetic database note",
                content: "Database transactions commit all operations together or roll back all operations together. Isolation controls concurrent changes.")
            var initial = fixture.app.settings
            initial.enableVectorRAG = true
            initial.forceHybridRAG = true
            initial.embeddingProviderKind = .mock
            initial.embeddingModelName = original.modelName
            initial.hybridSemanticWeight = 0.8
            initial.hybridKeywordWeight = 0.2
            fixture.app.settings = initial
            let observations = LiveRAGConfigurationObservations()
            let service = HybridContextRetrievalService(documentRepository: documents,
                configurationProvider: { [weak app = fixture.app] in
                    guard let app else { return (.default, nil) }
