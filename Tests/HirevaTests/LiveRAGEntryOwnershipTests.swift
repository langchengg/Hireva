private final class LiveRAGCooperativeGate: ContextRetrievalService, Sendable {
    private struct State: Sendable { var calls = 0; var cancellation = false; var exited = false }
    private let state = OSAllocatedUnfairLock(initialState: State())
    let entered = AsyncStream<Void>.makeStream(bufferingPolicy: .bufferingNewest(1))
    private let released = AsyncStream<Void>.makeStream(bufferingPolicy: .bufferingNewest(1))
    var callCount: Int { state.withLock { $0.calls } }
    var observedCancellation: Bool { state.withLock { $0.cancellation } }
    var exited: Bool { state.withLock { $0.exited } }
    func release() { released.continuation.yield(()); released.continuation.finish() }
    func retrieveContextWithTrace(question: String, intent: QuestionIntent, maxCVWords: Int,
        maxJDWords: Int, strategy: AnswerStrategy?) async throws -> (context: RetrievedContext, trace: RetrievalTrace) {
        state.withLock { $0.calls += 1 }
        defer { state.withLock { $0.exited = true } }
        entered.continuation.yield(()); entered.continuation.finish()
        await withTaskCancellationHandler {
            var iterator = released.stream.makeAsyncIterator()
            _ = await iterator.next()
        } onCancel: { self.state.withLock { $0.cancellation = true } }
        try Task.checkCancellation()
        return (RetrievedContext(cvChunks: [], jobDescriptionChunks: []),
            RetrievalTrace(id: UUID(), query: question, intent: intent.rawValue, createdAt: Date(),
                rankedCVChunks: [], rankedJDChunks: [], includedCVChunks: [], includedJDChunks: [],
                excludedCVChunks: [], excludedJDChunks: [], cvWordsUsed: 0, jdWordsUsed: 0,
                cvWordBudget: maxCVWords, jdWordBudget: maxJDWords, retrievalLatencyMS: 0,
                emptyQueryFallbackUsed: false, zeroScoreFallbackUsed: false))
    }
}

private final class LiveRAGHeldRoutingProvider: LocalLLMProvider {
    let id = "synthetic-held-routing"
    var displayName: String { id }
    let entered = AsyncStream<Void>.makeStream(bufferingPolicy: .bufferingNewest(1))
    private let released = AsyncStream<Void>.makeStream(bufferingPolicy: .bufferingNewest(1))
    private let answerProvider: ManualSnapshotLocalProvider
    init(answerProvider: ManualSnapshotLocalProvider) { self.answerProvider = answerProvider }
    func release() { released.continuation.yield(()); released.continuation.finish() }
    func healthCheck(modelName: String) async -> LocalLLMHealth {
        .init(ollamaRunning: true, selectedModel: modelName, modelInstalled: true, providerSource: .localQwen, lastError: nil)
    }
    func pullModel(_ modelName: String) -> AsyncThrowingStream<ModelDownloadProgress, Error> { AsyncThrowingStream { $0.finish() } }
    func generateAnswer(request: LocalLLMRequest) async throws -> AsyncThrowingStream<LLMToken, Error> {
        // Hold only the existing schema-bearing router transport. The answer
        // delegates to the ordinary fixture provider, without copying policy.
        if request.responseSchema == nil { return try await answerProvider.generateAnswer(request: request) }
        entered.continuation.yield(()); entered.continuation.finish()
        var iterator = released.stream.makeAsyncIterator()
        _ = await iterator.next()
        try Task.checkCancellation()
        return try await HermeticQuestionRoutingProvider().generateAnswer(request: request)
    }
}

private final class LiveRAGEmbeddingProbe: EmbeddingProvider {
    let providerID: String
    let modelName: String
    private let observations = OSAllocatedUnfairLock(initialState: [Bool]())
    init(providerID: String, modelName: String) { self.providerID = providerID; self.modelName = modelName }
    var dimension: Int { get async throws { 2 } }
    var calls: Int { observations.withLock { $0.count } }
    var mainThreadObservations: [Bool] { observations.withLock { $0 } }
    func embed(text: String) async throws -> [Float] {
        try Task.checkCancellation()
        observations.withLock { $0.append(Thread.isMainThread) }
        return [1, 0]
    }
    func embedBatch(texts: [String]) async throws -> [[Float]] {
        var result: [[Float]] = []
        for text in texts { result.append(try await embed(text: text)) }
        return result
    }
}

