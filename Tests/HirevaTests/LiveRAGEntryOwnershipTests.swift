    @Test(.timeLimit(.minutes(1)), arguments: PublicEntry.allCases)
    func publicManualEntriesFreezeRetrievalBeforeTheirQueuedWorkersStart(entry: PublicEntry) async throws {
        let fixture = try await ManualSnapshotFixture()
        let original = LiveRAGEmbeddingProbe(providerID: "synthetic-submitted-embedding", modelName: "synthetic-submitted-model")
        let replacement = LiveRAGEmbeddingProbe(providerID: "synthetic-later-embedding", modelName: "synthetic-later-model")
        var pending: Task<Void, Never>?
        do {
            let documents = DocumentRepository(database: fixture.database)
            _ = try documents.saveDocument(type: .cv, title: "Synthetic atomicity note",
                content: "Database transactions commit all operations together or roll back all operations together. Isolation controls concurrent changes.")
            var initial = fixture.app.settings
            initial.enableVectorRAG = true
            initial.forceHybridRAG = true
            initial.embeddingProviderKind = .mock
            initial.embeddingModelName = original.modelName
            fixture.app.settings = initial
            let observations = LiveRAGConfigurationObservations()
            fixture.app.contextRetrievalService = HybridContextRetrievalService(documentRepository: documents,
                configurationProvider: { [weak app = fixture.app] in
                    guard let app else { return (.default, nil) }
                    let settings = app.settings
                    let provider: any EmbeddingProvider = settings.embeddingModelName == original.modelName ? original : replacement
                    observations.record(settings: settings, provider: provider)
                    return (settings, provider)
                })
            let text = "Explain database transactions and atomicity."
            fixture.setTranscript(text)
            switch entry {
            case .answerNow:
                fixture.app.manualAnswerNow()
                let requiredAnswerNowWorker: Task<Void, Never> = try #require(fixture.app.activeAITask)
                pending = requiredAnswerNowWorker
            case .capture:
                fixture.app.manualCaptureState = .transcriptReady
                fixture.app.manualCaptureTranscript = text
                fixture.app.sendManualCaptureToAI()
                let requiredCaptureWorker: Task<Void, Never> = try #require(fixture.app.stageBTask)
                pending = requiredCaptureWorker
            case .manualRetry:
                fixture.app.manualCaptureState = .suggestionError("Synthetic previous model failure")
                fixture.app.manualCaptureTranscript = text
                // This is the real Manual workspace's Retry LLM button action.
                fixture.app.sendManualCaptureToAI(forceDeepSeek: false)
                let requiredRetryWorker: Task<Void, Never> = try #require(fixture.app.stageBTask)
                pending = requiredRetryWorker
            case .regenerate:
                var card = fixture.parent(id: "synthetic-visible-atomicity",
                    answer: "Atomicity means all transaction operations commit together or roll back together.")
                card.questionText = text
                fixture.app.currentSuggestion = card
                fixture.app.regenerateVisibleSuggestion()
                let requiredRegenerateWorker: Task<Void, Never> = try #require(fixture.app.activeAITask)
                pending = requiredRegenerateWorker
            }
            // No suspension since the actual user entry. A queued worker cannot
            // have resolved Hybrid configuration on MainActor yet.
            var changed = initial
            changed.enableVectorRAG = false
            changed.forceHybridRAG = false
            changed.embeddingProviderKind = .disabled
            changed.embeddingModelName = replacement.modelName
            fixture.app.settings = changed
            let request = try #require(pending)
            try await fixture.join(request)
            #expect(observations.models == [original.modelName])
            #expect(observations.providerIDs == [original.providerID])
            #expect(original.calls == 1)
            #expect(replacement.calls == 0)
            #expect(fixture.app.lastRetrievalTrace?.embeddingModel == original.modelName)
            #expect(fixture.app.currentSuggestion?.sayFirstSource == "ollama_qwen")
            #expect(fixture.remote.requests().isEmpty)
            try await fixture.close([request])
        } catch {
            pending?.cancel()
            await pending?.value
            try? await fixture.close(pending.map { [$0] } ?? [])
            throw error
        }
    }

    @Test(.timeLimit(.minutes(1)), arguments: [false, true])
    func queuedManualCannotConsumeANewerPrefetchAfterRAGConfigurationRevocation(restoreOriginalConfiguration: Bool) async throws {
        let fixture = try await ManualSnapshotFixture(useAnswerProviderForRouting: true)
        let routing = LiveRAGHeldRoutingProvider(answerProvider: fixture.original)
        let original = LiveRAGEmbeddingProbe(providerID: "synthetic-frozen-query", modelName: "synthetic-frozen-model")
        let replacement = LiveRAGEmbeddingProbe(providerID: "synthetic-new-query", modelName: "synthetic-new-model")
        var request: Task<Void, Never>?
        var prefetch: Task<Void, Never>?
        try await withTaskCancellationHandler {
            do {
                let documents = DocumentRepository(database: fixture.database)
                _ = try documents.saveDocument(type: .additionalNotes, title: "Synthetic transaction mechanism",
                    content: "A transaction commits all operations together or rolls them all back. Isolation controls concurrent visibility.")
                var initial = fixture.app.settings
                initial.manualOnlyMode = true
                initial.automaticQuestionDetectionEnabled = false
                initial.audioCaptureMode = .systemAudioOnly
                initial.enableVectorRAG = true
                initial.forceHybridRAG = true
                initial.embeddingProviderKind = .mock
                initial.embeddingModelName = original.modelName
                fixture.app.saveSettings(initial)
                fixture.app.contextRetrievalService = HybridContextRetrievalService(documentRepository: documents,
                    configurationProvider: { [weak app = fixture.app] in
                        guard let app else { return (.default, nil) }
                        let settings = app.settings
                        let provider: any EmbeddingProvider = settings.embeddingModelName == original.modelName ? original : replacement
                        return (settings, provider)
                    })
                fixture.app.localLLMProviderOverride = routing
                fixture.setTranscript("Can you explain how transaction atomicity handles partial failures?")
                fixture.app.manualAnswerNow()
                let pending = try #require(fixture.app.activeAITask)
                request = pending
                _ = try await TestEventWaitTrace(label: "prefetch.manual-cache-submission")
                    .nextEvent(in: routing.entered.stream, event: "router-entered")
                let frozenQuestion = try #require(fixture.app.lastDetectedQuestion)
                let segmentID = try #require(frozenQuestion.transcriptSegmentID)
                var next = initial
                next.embeddingModelName = replacement.modelName
                fixture.app.saveSettings(next)
                if restoreOriginalConfiguration { fixture.app.saveSettings(initial) }
                // An actual final transcript entry fills the replacement cache
                // while the older submitted Manual request is still held in routing.
                await fixture.app.handleTranscriptSegment(.init(id: segmentID, sessionID: fixture.session.id,
                    source: .systemAudio, speaker: .interviewer, text: frozenQuestion.questionText,
                    asrFinalizationReason: "final"))
                let worker = try #require(fixture.app.precomputeDebounceTask)
                prefetch = worker; await worker.value
                #expect(replacement.calls == (restoreOriginalConfiguration ? 0 : 1))
                #expect(original.calls == (restoreOriginalConfiguration ? 1 : 0))
                #expect(fixture.app.precomputedRAGCache.count == 1)
                routing.release()
                try await fixture.join(pending)
                #expect(original.calls == (restoreOriginalConfiguration ? 2 : 1),
                    "The submitted request must execute its frozen retriever; restoring identical settings cannot revive the revoked cache admission.")
                #expect(replacement.calls == (restoreOriginalConfiguration ? 0 : 1))
                #expect(fixture.app.lastRetrievalTrace?.embeddingModel == original.modelName)
                #expect(fixture.app.currentSuggestion?.sayFirstSource == "ollama_qwen")
                #expect(fixture.remote.requests().isEmpty)
                try await fixture.close([pending])
            } catch {
                routing.release(); prefetch?.cancel(); request?.cancel()
                await prefetch?.value; await request?.value
                try? await fixture.close(request.map { [$0] } ?? [])
                throw error
            }
        } onCancel: { routing.release() }
    }

