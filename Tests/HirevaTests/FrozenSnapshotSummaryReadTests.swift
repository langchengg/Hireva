import Foundation
import GRDB
import Testing
@testable import Hireva

@MainActor
struct FrozenSnapshotSummaryReadTests {
    @Test(arguments: [0, 2, 3])
    func frozenRequestDoesNotReadLaterLiveDocumentSummaries(emptyStreams: Int) async throws {
        let trace = TestEventWaitTrace(label: "FrozenSummary.\(emptyStreams)")
        trace.mark("body.enter")
        defer { trace.mark("body.exit") }
        let database = try TestSupport.makeTemporaryDatabase(prefix: "FrozenSnapshotSummary")
        let local = SnapshotSummaryLocalProvider(emptyStreams: emptyStreams)
        let app = AppState(database: database,
            questionRoutingProvider: HermeticQuestionRoutingProvider(),
            contextRetrievalService: SnapshotSummaryRetrieval(), dialogueDefaults: nil)
        app.answerProviderModeOverride = .localQwenPrimary
        app.localLLMProviderOverride = local
        let clock = ControlledGenerationWatchdogClock()
        app.generationWatchdogDelayProvider = clock
        let reads = AsyncStream<Void>.makeStream()
        var pending: Task<Void, Error>?
        do {
            let session = try app.createContextBoundSession(mode: .mock)
            app.currentSession = session
            let snapshotID = try #require(session.contextSnapshotID)
            let question = DetectedQuestion(id: UUID().uuidString, sessionID: session.id,
                transcriptSegmentID: nil, questionText: "Explain database transactions and atomicity.",
                intent: .technical, answerStrategy: .directAnswer, confidence: 1,
                reason: "Synthetic frozen summary fixture", shouldTrigger: true, questionComplete: true,
                modelName: "fixture", promptVersion: "fixture", createdAt: Date())
            try app.suggestionRepository.saveDetectedQuestion(question)

            // These documents were added after the empty session snapshot. They
            // must neither enter its prompt nor become a redundant live I/O input.
            let cvCanary = "LATER_LIVE_CV_SUMMARY_CANARY"
            let jdCanary = "LATER_LIVE_JD_SUMMARY_CANARY"
            _ = try app.documentRepository.saveDocument(type: .cv, title: "Synthetic later resume",
                content: "\(cvCanary): Synthetic candidate material added after this request's context was frozen. No real candidate data is used.")
            _ = try app.documentRepository.saveDocument(type: .jobDescription, title: "Synthetic later role",
                content: "\(jdCanary): Synthetic role requirements added after this request's context was frozen. No real job material is used.")

            try await database.dbQueue.write { db in
                db.trace(options: .statement) { event in
                    guard case let .statement(statement) = event else { return }
                    // Inspect unexpanded SQL locally. The trace emits only a count
                    // event; arguments and document contents are never logged.
                    let sql = statement.sql.uppercased()
                    if sql.contains("SELECT") && sql.contains("FROM DOCUMENTS WHERE TYPE") {
                        reads.continuation.yield(())
                    }
                }
            }
            let request = Task {
                try await app.generateSuggestion(for: question, session: session,
                    transcript: question.questionText, autoGenerated: false)
            }
            pending = request
            // A cooperative fixture safety limit, independent of product
            // deadlines. This fake retrieval/provider do not hold resources.
            try await GenerationCoordinator.withTimeout(seconds: 30) {
                try await withTaskCancellationHandler {
                    try await request.value
                } onCancel: {
                    request.cancel()
                }
            }
            try await database.dbQueue.write { $0.trace(options: []) }
            reads.continuation.finish()
            var liveDocumentReads = 0
            for await _ in reads.stream { liveDocumentReads += 1 }
            let providerRequests = await local.requests()
            trace.mark("request.terminal.parser_checked")
            #expect(providerRequests.count == emptyStreams + 1)
            #expect(liveDocumentReads == 0,
                "A frozen snapshot must not query live CV/JD documents whose summaries it discards.")
            #expect(providerRequests.allSatisfy { !$0.prompt.contains(cvCanary) && !$0.prompt.contains(jdCanary) })
            #expect(providerRequests.allSatisfy { $0.prompt.contains("SOURCE_NOTE_CANARY") && $0.prompt.contains("unverified; not candidate history") })
            #expect(app.currentSuggestion?.ragChunkIDs.contains("frozen-task-note") == true)
            #expect(app.currentSuggestion?.evidenceUsed.contains("frozen-task-note") == true)
            #expect(app.currentSuggestionRetrievedChunks.map(\.id) == ["frozen-task-note"])
            #expect(app.currentSuggestionRetrievedChunks.first?.fullContent.contains("SOURCE_NOTE_CANARY") == true)
            #expect(app.currentSuggestion?.candidateEvidenceIDs.isEmpty == true)
            #expect(app.currentSuggestion?.contextSnapshotID == snapshotID)
            #expect(app.currentSuggestion?.sayFirstSource == "ollama_qwen")
            let cardID = try #require(app.currentSuggestion?.id)
            await app.generationCoordinator.drainRetiredTasks()
            let savedSources = try app.suggestionRepository.retrievedChunks(suggestionCardID: cardID)
            #expect(savedSources.map(\.id) == ["frozen-task-note"])
            #expect(savedSources.first?.fullContent.contains("SOURCE_NOTE_CANARY") == true)
            clock.cancelAll()
            await app.shutdownForTesting()
            try database.close()
        } catch {
            clock.cancelAll()
            pending?.cancel()
            _ = await pending?.result
            try? await database.dbQueue.write { $0.trace(options: []) }
            reads.continuation.finish()
            await app.shutdownForTesting()
            try? database.close()
            throw error
        }
    }
}

private struct SnapshotSummaryRetrieval: ContextRetrievalService {
    func retrieveContextWithTrace(question: String, intent: QuestionIntent, maxCVWords: Int,
        maxJDWords: Int, strategy: AnswerStrategy?) async throws -> (context: RetrievedContext, trace: RetrievalTrace) {
        try Task.checkCancellation()
        let note = DocumentChunk(id: "frozen-task-note", documentID: "synthetic-task-reference", documentType: .additionalNotes,
            chunkIndex: 0, content: "SOURCE_NOTE_CANARY: Database transaction behavior depends on the specified operation conditions.",
            keywords: ["database", "transaction"], sectionTitle: "Database transactions", wordCount: 13,
            metadataJSON: nil, createdAt: Date(timeIntervalSince1970: 1))
        return (RetrievedContext(cvChunks: [], jobDescriptionChunks: [], additionalNotesChunks: [note]),
            RetrievalTrace(id: UUID(), query: question, intent: intent.rawValue, createdAt: Date(),
                rankedCVChunks: [], rankedJDChunks: [], includedCVChunks: [], includedJDChunks: [],
                excludedCVChunks: [], excludedJDChunks: [], cvWordsUsed: 0, jdWordsUsed: 0,
                cvWordBudget: maxCVWords, jdWordBudget: maxJDWords, retrievalLatencyMS: 0,
                emptyQueryFallbackUsed: false, zeroScoreFallbackUsed: false))
    }
}

private actor SnapshotSummaryLocalProvider: LocalLLMProvider {
    nonisolated var id: String { "snapshot-summary-local" }
    nonisolated var displayName: String { id }
    private var captured: [LocalLLMRequest] = []
    private var emptyStreams: Int
    init(emptyStreams: Int) { self.emptyStreams = emptyStreams }
    func requests() -> [LocalLLMRequest] { captured }
    func healthCheck(modelName: String) async -> LocalLLMHealth {
        .init(ollamaRunning: true, selectedModel: modelName, modelInstalled: true,
            providerSource: .ollamaQwen, lastError: nil)
    }
    nonisolated func pullModel(_ modelName: String) -> AsyncThrowingStream<ModelDownloadProgress, Error> {
        AsyncThrowingStream { $0.finish() }
    }
    func generateAnswer(request: LocalLLMRequest) async throws -> AsyncThrowingStream<LLMToken, Error> {
        try Task.checkCancellation()
        captured.append(request)
        if emptyStreams > 0 {
            emptyStreams -= 1
            return AsyncThrowingStream { $0.finish() }
        }
        return AsyncThrowingStream { continuation in
            continuation.yield(.init(text: "A database transaction groups operations into an atomic unit. Atomicity means all operations commit together or roll back together, and isolation controls which concurrent changes each transaction can observe.",
                source: .ollamaQwen, modelName: request.modelName))
            continuation.finish()
        }
    }
}
