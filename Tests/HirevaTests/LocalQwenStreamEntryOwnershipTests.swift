/// Invokes the existing production entry before its ownership patch. It does
/// not depend on generateLocalAnswer or copy any answer acceptance rule.
@MainActor
struct LocalQwenStreamEntryOwnershipTests {
    @Test(.timeLimit(.minutes(1)), arguments: ["startup", "stream", "completed"])
    func actualLiveLocalEntryHasOneDeadlineAcrossProviderStartupAndStream(_ scenario: String) async throws {
        let fixture = try await ManualSnapshotFixture()
        let provider = ControlledLocalAnswerProvider(id: "synthetic-live-deadline")
        let observed = AsyncStream<Void>.makeStream(bufferingPolicy: .bufferingOldest(1))
        let subscription = fixture.app.$ollamaDiagnostics.filter { $0.contentChunksReceived > 0 }
            .sink { _ in observed.continuation.yield(()) }
        var pending: Task<Void, Error>?
        func cleanup() async throws {
            subscription.cancel(); observed.continuation.finish()
            fixture.clock.cancelAll()
            pending?.cancel()
            await provider.releaseAll()
            _ = await pending?.result
            try await fixture.close([])
        }
        do {
            let question = DetectedQuestion(id: UUID().uuidString, sessionID: fixture.session.id,
                transcriptSegmentID: nil, questionText: "Explain database transactions and atomicity.",
                intent: .technical, answerStrategy: .directAnswer, confidence: 1,
                reason: "Synthetic Live local deadline", shouldTrigger: true, questionComplete: true,
                modelName: "fixture", promptVersion: "fixture", createdAt: Date())
            let task = Task {
                try await fixture.app.generateSuggestion(for: question, session: fixture.session,
                    transcript: question.questionText, autoGenerated: true,
                    localProvider: provider, localModelName: fixture.originalModel)
            }
            pending = task
            #expect(try await provider.nextStart() == 1)
            let identity = try #require(fixture.app.activeGenerationController?.identity)
            let child = try #require(fixture.app.generationCoordinator.stageATask)
            let watchdog = try #require(fixture.app.fullCardWatchdogTask)
            let period = fixture.app.generationFullCardWatchdogNanoseconds
            try await fixture.clock.waitUntilPending(nanoseconds: period)
            #expect(fixture.clock.requestedNanoseconds.filter { $0 == period }.count == 1)
            if scenario != "startup" {
                await provider.gate.release(1)
                #expect(try await provider.nextStream() == 1)
                #expect(provider.emit(scenario == "completed" ? Self.answer : "A database transaction ",
                    ordinal: 1, model: fixture.originalModel))
                if scenario == "stream" {
                    _ = try await TestEventWaitTrace(label: "live-local-deadline.partial-consumed")
                        .nextEvent(in: observed.stream, event: "content-diagnostic")
                    #expect(fixture.app.ollamaDiagnostics.contentChunksReceived == 1)
                }
                if scenario == "completed" {
                    provider.finish(ordinal: 1)
                    try await task.value
                    await watchdog.value
                    let card = try #require(fixture.app.currentSuggestion)
                    #expect(card.sayFirst == Self.answer)
                    #expect(card.generationID == identity.generationID)
                    let terminal = fixture.app.generationUIState
                    fixture.clock.advance(by: period)
                    #expect(fixture.app.generationUIState == terminal)
                    #expect(watchdog.isCancelled)
                }
            }
            if scenario != "completed" {
                fixture.clock.advance(by: period)
                await watchdog.value
                if case .timeout = fixture.app.generationUIState {} else { Issue.record("Unfinished local stream must time out") }
                #expect(child.isCancelled)
                #expect(!fixture.app.generationCoordinator.canPublish(identity))
                #expect(fixture.app.currentSuggestion == nil)
                #expect(!fixture.app.softFallbackUsed)
                #expect(!fixture.app.isActionLoading(ActionID.generateAnswer))
            }
            #expect(fixture.remote.requests().isEmpty)
            #expect(try fixture.app.suggestionRepository.suggestions(sessionID: fixture.session.id).isEmpty)
            try await cleanup()
            #expect(fixture.app.generationCoordinator.pendingCleanupTaskCount == 0)
        } catch {
            try? await cleanup()
            throw error
        }
    }

    @Test(.timeLimit(.minutes(1)))
    func asynchronousFixturePreparationKeepsMigratedQueuesIndependent() async throws {
        let first = try await TestSupport.makeInMemoryDatabase()
        defer { try? first.close() }
        let second = try await TestSupport.makeInMemoryDatabase()
        defer { try? second.close() }
        #expect(first.dbQueue !== second.dbQueue)
        #expect(first.databaseURL == nil && second.databaseURL == nil)
        var settings = AppSettings.default
        settings.saveTranscriptsLocally = false
        try SettingsRepository(database: first).saveSettings(settings)
        settings.saveTranscriptsLocally = true
        try SettingsRepository(database: second).saveSettings(settings)
        #expect(try SettingsRepository(database: first).loadSettings().saveTranscriptsLocally == false)
        try first.close()
        #expect(try SettingsRepository(database: second).loadSettings().saveTranscriptsLocally)
    }

    @Test(.timeLimit(.minutes(1)))
    func localEntryRetainsTheActualStartingProviderUntilItExits() async throws {
        let fixture = try await LocalQwenOwnedEntryFixture()
        var request: Task<Bool, Error>?
        do {
            let pending = Task { try await fixture.finishLocal() }
            request = pending
            #expect(try await fixture.provider.nextStart() == 1)
            let child = fixture.app.generationCoordinator.stageATask
            #expect(child != nil, "Provider startup must already have an authoritative owned child.")
            #expect(fixture.app.generationCoordinator.pendingCleanupTaskCount == 1)
