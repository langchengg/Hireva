final class ControlledLocalAnswerProvider: LocalLLMProvider, Sendable {
    let id: String
    let displayName = "Synthetic controlled local answer provider"
    let gate = ControlledLocalAnswerStartupGate()
    let ready = AsyncStream<Int>.makeStream(bufferingPolicy: .bufferingOldest(8))
    private struct State: Sendable {
        var streams: [Int: AsyncThrowingStream<LLMToken, Error>.Continuation] = [:]
        var terminations: [Int: String] = [:]
        var closed = false
    }
    private let state = OSAllocatedUnfairLock(initialState: State())
    init(id: String) { self.id = id }
    func healthCheck(modelName: String) async -> LocalLLMHealth {
        .init(ollamaRunning: true, selectedModel: modelName, modelInstalled: true,
            providerSource: .ollamaQwen, lastError: nil)
    }
    func pullModel(_ modelName: String) -> AsyncThrowingStream<ModelDownloadProgress, Error> {
        AsyncThrowingStream { $0.finish() }
    }
    func generateAnswer(request: LocalLLMRequest) async throws -> AsyncThrowingStream<LLMToken, Error> {
        let ordinal = await gate.hold(request)
        let pair = AsyncThrowingStream<LLMToken, Error>.makeStream()
        pair.continuation.onTermination = { [weak self] termination in
            self?.state.withLock { state in
                state.streams.removeValue(forKey: ordinal)
                switch termination {
                case .cancelled: state.terminations[ordinal] = "cancelled"
                case .finished: state.terminations[ordinal] = "finished"
                @unknown default: state.terminations[ordinal] = "unknown"
                }
            }
        }
        let closed = state.withLock { state -> Bool in
            guard !state.closed else { return true }
            state.streams[ordinal] = pair.continuation
            return false
        }
        if closed { pair.continuation.finish(throwing: CancellationError()) }
        ready.continuation.yield(ordinal)
        return pair.stream
    }
    func nextStart() async throws -> Int {
        try await TestEventWaitTrace(label: "local-provider-startup")
            .nextEvent(in: gate.started.stream, event: "entered")
    }
    func nextStream() async throws -> Int {
        try await TestEventWaitTrace(label: "local-provider-stream")
            .nextEvent(in: ready.stream, event: "created")
    }
    @discardableResult
    func emit(_ text: String, ordinal: Int, model: String = "synthetic-frozen-model") -> Bool {
        guard let continuation = state.withLock({ $0.streams[ordinal] }) else { return false }
        switch continuation.yield(.init(text: text, source: .ollamaQwen, modelName: model)) {
        case .enqueued: return true
        case .dropped, .terminated: return false
        @unknown default: return false
        }
    }
    func finish(ordinal: Int, error: Error? = nil) {
        state.withLock { $0.streams[ordinal] }?.finish(throwing: error)
    }
    func terminationKind(ordinal: Int) -> String? { state.withLock { $0.terminations[ordinal] } }
    func openStreamCount() -> Int { state.withLock { $0.streams.count } }
    func releaseAll() async {
        let held = state.withLock { state in
            state.closed = true
            let held = Array(state.streams.values)
            state.streams.removeAll()
            return held
        }
        held.forEach { $0.finish(throwing: CancellationError()) }
        await gate.releaseAll()
        ready.continuation.finish()
    }
}

actor ControlledLocalAnswerStartupGate {
    nonisolated let started = AsyncStream<Int>.makeStream(bufferingPolicy: .bufferingOldest(8))
    private var captured: [LocalLLMRequest] = []
    private var waiters: [Int: CheckedContinuation<Void, Never>] = [:]
    private var released = Set<Int>()
    private var closed = false
    func calls() -> [LocalLLMRequest] { captured }
    func pendingCount() -> Int { waiters.count }
    func hold(_ request: LocalLLMRequest) async -> Int {
        captured.append(request)
        let ordinal = captured.count
        started.continuation.yield(ordinal)
        if !closed && !released.contains(ordinal) {
            await withCheckedContinuation { waiters[ordinal] = $0 }
        }
        return ordinal
    }
    func release(_ ordinal: Int) { released.insert(ordinal); waiters.removeValue(forKey: ordinal)?.resume() }
    func releaseAll() {
        closed = true
        let pending = Array(waiters.values)
        waiters.removeAll()
        pending.forEach { $0.resume() }
        started.continuation.finish()
    }
}
